// Strata backend: Judas drives the `strata --serve` engine (github.com/Niko1221/Strata, MIT) as a child process.
// Strata owns the model, the per-expert GPU cache and the MTP drafting; Judas owns everything around a token id:
// the chat template, tokenization (through libllama, on a vocab-only model, no GPU), sampling parameters, output
// parsing (reasoning, tool calls), queuing agents onto the single sequence the engine serves, cancel and streaming.
// Design and trade-offs: docs/STRATA-BACKEND.md. Pure mapping logic: strata_proto.{h,cpp}.

