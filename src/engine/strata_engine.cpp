using clk = std::chrono::steady_clock;
double secs_since(clk::time_point t) { return std::chrono::duration<double>(clk::now() - t).count(); }

long read_sysfs_mib(const char * path) {
    std::ifstream f(path);
    long v = -1;
    if (f >> v) return v / 1048576;
    return -1;
}

common_chat_msg to_common(const ChatMessage & m) {
    common_chat_msg c;
    c.role = m.role;
    c.content = m.content;
    c.reasoning_content = m.reasoning;
    for (const auto & tc : m.tool_calls) {
        std::string args = tc.arguments;
        if (!json::accept(args.empty() ? "{}" : args))
            args = json({{"invalid_json_truncated", args.substr(0, 200)}}).dump();
        c.tool_calls.push_back({tc.name, args, tc.id});
    }
    c.tool_call_id = m.tool_call_id;
    c.tool_name = m.tool_name;
    return c;
}

ChatMessage from_common(const common_chat_msg & c) {
    ChatMessage m;
    m.role = c.role.empty() ? "assistant" : c.role;
    m.content = c.content;
    m.reasoning = c.reasoning_content;
    for (const auto & tc : c.tool_calls) m.tool_calls.push_back({tc.id, tc.name, tc.arguments});
    return m;
}

// The tokenizer of Strata's model without loading it. The GGUF's architecture ("qwen4exp") is unknown to libllama,
// but its vocabulary is plain byte-level BPE with the qwen35 pre-tokenizer. Copy only the tokenizer.ggml.* keys and the chat template
// into a tiny synthetic GGUF that claims arch qwen35, and load that with vocab_only (no tensors, no GPU).
// Checked against Strata's reference tokenizer (tools/strata_tokenizer.py) on the same strings: identical ids.
llama_model * load_vocab_model(const std::string & gguf_path, const std::string & tmp_dir) {
    gguf_init_params ip{true, nullptr};
    gguf_context * src = gguf_init_from_file(gguf_path.c_str(), ip);
    if (!src) throw std::runtime_error("strata: cannot read GGUF metadata of " + gguf_path);
    if (gguf_find_key(src, "tokenizer.ggml.tokens") < 0) {
        gguf_free(src);
        throw std::runtime_error("strata: " + gguf_path + " carries no tokenizer");
    }
    gguf_context * d = gguf_init_empty();
    gguf_set_kv(d, src);
    gguf_free(src);
    std::vector<std::string> drop;
    for (int i = 0; i < gguf_get_n_kv(d); i++) {
        std::string k = gguf_get_key(d, i);
        if (k.rfind("tokenizer.ggml.", 0) != 0 && k != "tokenizer.chat_template") drop.push_back(k);
    }
    for (const auto & k : drop) gguf_remove_key(d, k.c_str());
    gguf_set_val_str(d, "general.architecture", "qwen35");
    gguf_set_val_u32(d, "qwen35.block_count", 1);
    gguf_set_val_u32(d, "qwen35.context_length", 4096);
    gguf_set_val_u32(d, "qwen35.embedding_length", 64);
    std::filesystem::create_directories(tmp_dir);
    std::string out = tmp_dir + "/strata-vocab-" + std::to_string(getpid()) + ".gguf";
    bool ok = gguf_write_to_file(d, out.c_str(), false);
    gguf_free(d);
    if (!ok) throw std::runtime_error("strata: cannot write " + out);
    llama_model_params mp = llama_model_default_params();
    mp.vocab_only = true;
    mp.n_gpu_layers = 0;
    static ggml_backend_dev_t no_devices[] = {nullptr};   // never touch the GPU from the tokenizer
    mp.devices = no_devices;
    llama_model * m = llama_model_load_from_file(out.c_str(), mp);
    std::error_code ec;
    std::filesystem::remove(out, ec);
    if (!m) throw std::runtime_error("strata: cannot load the tokenizer from " + gguf_path);
    return m;
}

class StrataEngine final : public Engine {
public:
    explicit StrataEngine(const Config & cfg) : cfg_(cfg), m_(cfg.active_model()), name_(cfg.engine.model) {
        if (!getenv("JUDAS_DEBUG"))
            llama_log_set([](ggml_log_level level, const char * t, void *) { if (level >= GGML_LOG_LEVEL_ERROR) fputs(t, stderr); },
                          nullptr);
        llama_backend_init();
        path_ = expand_home(m_.path);
        std::string data = expand_home(cfg.data_dir);
        vocab_model_ = load_vocab_model(path_, data);
        vocab_ = llama_model_get_vocab(vocab_model_);

        // Template: an explicit chat_template_file, else the one inside the model's GGUF, else the pack's copy.
        std::string tmpl;
        auto read_file = [](const std::string & f) {
            std::ifstream in(f);
            return std::string(std::istreambuf_iterator<char>(in), {});
        };
        if (!m_.chat_template_file.empty()) tmpl = read_file(expand_home(m_.chat_template_file));
        if (tmpl.empty()) {
            const char * emb = llama_model_chat_template(vocab_model_, nullptr);
            if (emb) tmpl = emb;
        }
        if (tmpl.empty()) {
            std::string tpath = strata_chat_template_path(m_);
            if (!tpath.empty()) tmpl = read_file(tpath);
        }
        if (tmpl.empty()) throw std::runtime_error("strata: no chat template (the GGUF has none; set chat_template_file)");
        tmpls_ = common_chat_templates_init(nullptr, tmpl);

        if (!m_.logit_bias.empty() || !m_.bias_file.empty())
            std::fprintf(stderr, "judas: strata backend ignores logit_bias/bias_file (the engine has no logit bias)\n");
        if (cfg.engine.max_agents > 1)
            std::fprintf(stderr, "judas: strata serves one sequence; %d agents will take turns\n", cfg.engine.max_agents);

        start_process(data);
        for (;;) {   // up to 20 minutes: the first load pins tens of GB
            StrataLine l;
            if (!next_line(l, 1000, nullptr)) {
                if (eof_.load()) throw std::runtime_error("strata engine exited while loading (see " + log_path_ + ")");
                if (secs_since(t_start_) > 1200) throw std::runtime_error("strata engine did not become ready in 20 minutes");
                continue;
            }
            if (l.kind == StrataLine::Ready) {
                can_stop_ = l.can_stop;
                max_context_ = l.max_context;
                break;
            }
        }
    }

    ~StrataEngine() override {
        if (pid_ > 0) {
            ssize_t w = write(in_fd_, "QUIT\n", 5);
            (void) w;
            close(in_fd_);
            in_fd_ = -1;
            for (int i = 0; i < 300; i++) {   // up to 30 s for the engine to free its GPU and RAM
                if (waitpid(pid_, nullptr, WNOHANG) != 0) { pid_ = -1; break; }
                std::this_thread::sleep_for(std::chrono::milliseconds(100));
            }
            if (pid_ > 0) {
                kill(pid_, SIGTERM);
                for (int i = 0; i < 100; i++) {
                    if (waitpid(pid_, nullptr, WNOHANG) != 0) { pid_ = -1; break; }
                    std::this_thread::sleep_for(std::chrono::milliseconds(100));
                }
            }
            if (pid_ > 0) { kill(pid_, SIGKILL); waitpid(pid_, nullptr, 0); }
        }
        if (reader_.joinable()) reader_.join();
        if (out_fd_ >= 0) close(out_fd_);
        if (vocab_model_) llama_model_free(vocab_model_);
    }

    std::string model_name() const override { return name_; }

    int count_tokens(const std::string & text) const override {
        int n = -llama_tokenize(vocab_, text.c_str(), text.size(), nullptr, 0, false, true);
        return n < 0 ? -n : n;
    }

    EngineState state() const override {
        std::lock_guard lk(stat_mu_);
        EngineState s;
        s.model = name_;
        s.model_path = path_;
        s.loaded = !eof_.load();
        s.hybrid = true;
        s.max_agents = 1;
        s.active = active_;
        s.queued = (int) turn_.waiting();
        s.ctx_total = m_.ctx_total;
        s.ctx_used = ctx_used_;
        s.ctx_active = active_ ? ctx_used_ : 0;
        s.ctx_free = std::max(0, m_.ctx_total - ctx_used_);
        s.vram_used_mib = read_sysfs_mib("/sys/class/drm/card1/device/mem_info_vram_used");
        s.vram_total_mib = read_sysfs_mib("/sys/class/drm/card1/device/mem_info_vram_total");
        s.gen_tok_s = last_tps_;
        if (active_) s.seqs.push_back({0, cur_tag_, cur_phase_, ctx_used_, cur_prio_});
        s.total_prompt_tokens = total_p_;
        s.total_completion_tokens = total_c_;
        s.requests = requests_;
        return s;
    }

    ChatResult chat(const ChatRequest & req, const std::function<bool(const ChatDelta &)> & on_delta,
                    const std::atomic<bool> * cancel) override {
        ChatResult res;
        Prepared p;
        try {
            p = prepare(req);
        } catch (const std::exception & e) {
            res.finish_reason = "error";
            res.error = e.what();
            return res;
        }
        const int ctx = m_.ctx_total;
        if ((int) p.ids.size() + 1 >= ctx) {
            res.finish_reason = "error";
            res.error = "prompt is " + std::to_string(p.ids.size()) + " tokens, larger than the context (ctx_total " +
                        std::to_string(ctx) + "); shorten the conversation or raise ctx_total";
            return res;
        }
        int max_new = req.sampling.max_tokens > 0 ? req.sampling.max_tokens : cfg_.engine.max_tokens;
        max_new = std::max(1, std::min(max_new, ctx - (int) p.ids.size() - 1));

        auto t_submit = clk::now();
        if (!turn_.acquire(req.priority, cancel)) {
            res.finish_reason = "cancelled";
            return res;
        }
        struct Release {
            TicketQueue & q;
            ~Release() { q.release(); }
        } release{turn_};
        res.queue_s = secs_since(t_submit);
        {
            std::lock_guard lk(stat_mu_);
            active_ = 1;
            cur_tag_ = req.tag;
            cur_prio_ = req.priority;
            cur_phase_ = "prefill";
            ctx_used_ = (int) p.ids.size();
        }
        struct Idle {
            StrataEngine & e;
            ~Idle() { std::lock_guard lk(e.stat_mu_); e.active_ = 0; }
        } idle{*this};

        if (eof_.load()) {
            res.finish_reason = "error";
            res.error = "the strata engine is not running (see " + log_path_ + ")";
            return res;
        }
        StrataLine stale;
        while (next_line(stale, 0, nullptr)) {}   // anything left over from an aborted request
        std::string line = strata_gen_line(max_new, p.sampling, p.ids) + "\n";
        if (!write_all(line)) {
            res.finish_reason = "error";
            res.error = "the strata engine stopped unexpectedly (see " + log_path_ + ")";
            return res;
        }

        auto t0 = clk::now();
        clk::time_point t_first{};
        std::string text, pending_bytes;
        std::vector<std::string> tool_ids;
        common_chat_msg partial = common_chat_parse("", true, p.parser);
        size_t parsed_len = 0;
        int generated = 0, reused = 0;
        bool stopped = false, cancelled = false, saw_stop_token = false, errored = false, done = false;
        std::string err;
        StrataLine done_line;

        auto request_stop = [&] {
            if (stopped) return;
            stopped = true;
            if (can_stop_) write_all("STOP\n");
        };
        auto flush_delta = [&](bool final_parse) {
            // the throttled streaming parse (same cadence as the llama backend)
            if (!on_delta) return;
            ChatDelta d;
            try {
                if (!final_parse) {
                    size_t every = text.size() < 2048 ? 1 : std::min<size_t>(256, text.size() / 16);
                    if (text.size() - parsed_len < every) return;
                    parsed_len = text.size();
                }
                auto msg = common_chat_parse(text, !final_parse, p.parser);
                for (const auto & x : common_chat_msg_diff::compute_diffs(partial, msg)) {
                    d.content += x.content_delta;
                    d.reasoning += x.reasoning_content_delta;
                }
                partial = msg;
            } catch (...) {
                return;
            }
            if (d.content.empty() && d.reasoning.empty()) return;
            bool keep = true;
            try { keep = on_delta(d); } catch (...) {}
            if (!keep) { cancelled = true; request_stop(); }
        };

        while (!done) {
            StrataLine l;
            if (!next_line(l, 100, &errored)) {
                if (errored || eof_.load()) {
                    err = "the strata engine stopped unexpectedly (see " + log_path_ + ")";
                    errored = true;
                    break;
                }
                if (cancel && cancel->load() && !cancelled) { cancelled = true; request_stop(); }
                continue;
            }
            if (cancel && cancel->load() && !cancelled) { cancelled = true; request_stop(); }
            switch (l.kind) {
            case StrataLine::Resume:
            case StrataLine::Reused: reused = l.reused; break;
            case StrataLine::Prompt: {
                std::lock_guard lk(stat_mu_);
                cur_phase_ = "prefill";
                break;
            }
            case StrataLine::Token: {
                if (stopped) break;   // late tokens after STOP or a stop token
                if (!t_first.time_since_epoch().count()) {
                    t_first = clk::now();
                    res.prefill_s = std::chrono::duration<double>(t_first - t0).count();
                    std::lock_guard lk(stat_mu_);
                    cur_phase_ = "generate";
                }
                if (llama_vocab_is_eog(vocab_, l.token)) {
                    saw_stop_token = true;
                    request_stop();
                    break;
                }
                generated++;
                pending_bytes += piece(l.token);
                size_t n = utf8_complete_prefix(pending_bytes);
                text.append(pending_bytes, 0, n);
                pending_bytes.erase(0, n);
                for (const auto & s : p.stops) {
                    if (!s.empty() && text.size() >= s.size() && text.compare(text.size() - s.size(), s.size(), s) == 0) {
                        text.resize(text.size() - s.size());
                        saw_stop_token = true;
                        request_stop();
                        break;
                    }
                }
                if (!stopped) flush_delta(false);
                if (generated % 16 == 0) {
                    std::lock_guard lk(stat_mu_);
                    ctx_used_ = (int) p.ids.size() + generated;
                }
                break;
            }
            case StrataLine::Done: done_line = l; done = true; break;
            case StrataLine::Err: err = "strata: " + l.text; errored = true; done = true; break;
            default: break;
            }
        }
        text += pending_bytes;   // an incomplete sequence at the very end is kept as bytes

        res.prompt_tokens = (int) p.ids.size();
        res.cached_tokens = reused;
        res.completion_tokens = generated;
        res.generate_s = done_line.decode_ms > 0 ? done_line.decode_ms / 1000.0 : (t_first.time_since_epoch().count() ? secs_since(t_first) : 0);
        if (errored) {
            res.finish_reason = "error";
            res.error = err;
            return res;
        }
        common_chat_msg msg;
        try {
            msg = common_chat_parse(text, false, p.parser);
            msg.set_tool_call_ids(tool_ids, [&] { return "call_s" + std::to_string(++call_ids_); });
        } catch (...) {
            msg.role = "assistant";
            msg.content = text;
        }
        if (!cancelled) flush_delta(true);
        res.message = from_common(msg);
        std::string finish = cancelled ? "cancelled" : saw_stop_token ? "stop" : strata_finish_reason(done_line.finish);
        if (finish == "stop" && !res.message.tool_calls.empty()) finish = "tool_calls";
        res.finish_reason = finish;
        {
            std::lock_guard lk(stat_mu_);
            total_p_ += res.prompt_tokens - std::min(res.prompt_tokens, reused);
            total_c_ += generated;
            requests_++;
            if (res.generate_s > 0 && generated > 1) last_tps_ = generated / res.generate_s;
            ctx_used_ = res.prompt_tokens + generated;
        }
        return res;
    }

private:
    struct Prepared {
        std::vector<int> ids;
        common_chat_parser_params parser;
        std::vector<std::string> stops;
        StrataSampling sampling;
    };

    Prepared prepare(const ChatRequest & req) {
        Prepared p;
        common_chat_templates_inputs in;
        // Same handling of mid-conversation system messages as the llama backend (Qwen templates accept one, first).
        bool seen_nonsystem = false;
        for (const auto & m : req.messages) {
            common_chat_msg c = to_common(m);
            if (c.role == "system" && seen_nonsystem) {
                c.role = "user";
                c.content = "[system] " + c.content;
            } else if (c.role == "system" && !in.messages.empty()) {
                in.messages[0].content += "\n\n" + c.content;
                continue;
            }
            if (c.role != "system") seen_nonsystem = true;
            in.messages.push_back(std::move(c));
        }
        for (const auto & t : req.tools) in.tools.push_back({t.name, t.description, t.parameters.dump()});
        in.add_generation_prompt = true;
        in.use_jinja = true;
        in.enable_thinking = req.enable_thinking;
        in.reasoning_format = COMMON_REASONING_FORMAT_DEEPSEEK;
        in.parallel_tool_calls = true;
        for (const auto & [k, v] : m_.template_kwargs) in.chat_template_kwargs[k] = json(v).dump();
        auto params = common_chat_templates_apply(tmpls_.get(), in);

        bool add_bos = llama_vocab_get_add_bos(vocab_);
        int n = -llama_tokenize(vocab_, params.prompt.c_str(), params.prompt.size(), nullptr, 0, add_bos, true);
        std::vector<llama_token> toks(n);
        llama_tokenize(vocab_, params.prompt.c_str(), params.prompt.size(), toks.data(), n, add_bos, true);
        p.ids.assign(toks.begin(), toks.end());

        p.parser = common_chat_parser_params(params);
        p.parser.reasoning_format = COMMON_REASONING_FORMAT_DEEPSEEK;
        p.parser.parse_tool_calls = !req.tools.empty();
        if (!params.parser.empty()) p.parser.parser.load(params.parser);
        p.stops = params.additional_stops;
        p.sampling = strata_sampling(req.sampling.temp, req.sampling.top_p, req.sampling.min_p, req.sampling.top_k,
                                     req.sampling.seed, m_);
        return p;
    }

    std::string piece(llama_token t) const {
        char buf[256];
        int n = llama_token_to_piece(vocab_, t, buf, sizeof buf, 0, false);
        if (n < 0) {
            std::string big(-n, '\0');
            llama_token_to_piece(vocab_, t, big.data(), big.size(), 0, false);
            return big;
        }
        return std::string(buf, n);
    }

    // ---- the child process ----

    // strata_profile if set, else the profile compiled into judas, written once to <data_dir>/strata/.
    std::string resolve_profile(const std::string & data_dir) {
        if (!m_.strata_profile.empty()) return expand_home(m_.strata_profile);
        std::error_code ec;
        std::filesystem::create_directories(data_dir + "/strata", ec);
        std::string out = data_dir + "/strata/expert-profile.bin";
        if (!std::filesystem::exists(out, ec) || std::filesystem::file_size(out, ec) != strata_profile_size) {
            std::ofstream f(out, std::ios::binary | std::ios::trunc);
            f.write((const char *) strata_profile_data, (std::streamsize) strata_profile_size);
            if (!f) throw std::runtime_error("strata: cannot write " + out);
        }
        return out;
    }

    void start_process(const std::string & data_dir) {
        std::string profile = resolve_profile(data_dir);
        // The engine is this very binary: `judas __strata-engine --serve ...` (src/main.cpp calls Strata's main).
        std::vector<std::string> argv_s = {"/proc/self/exe", "__strata-engine"};
        // test hook: tests/strata_tokenizer_check.cpp points this at a script that speaks the protocol
        if (const char * fake = std::getenv("JUDAS_STRATA_FAKE_ENGINE"); fake && *fake) argv_s = {fake};
        for (auto & a : strata_argv(m_, m_.ctx_total, profile)) argv_s.push_back(a);
        std::error_code ec;
        std::filesystem::create_directories(data_dir + "/logs", ec);
        log_path_ = data_dir + "/logs/strata.log";
        int log_fd = open(log_path_.c_str(), O_WRONLY | O_CREAT | O_APPEND | O_CLOEXEC, 0644);
        std::vector<char *> argv;
        for (auto & a : argv_s) argv.push_back(a.data());
        argv.push_back(nullptr);
        // environment: the parent's, with ROCm's libraries on the library path
        std::vector<std::string> env_s;
        bool has_ld = false;
        for (char ** e = environ; e && *e; ++e) {
            std::string s = *e;
            if (s.rfind("LD_LIBRARY_PATH=", 0) == 0) { s += ":/opt/rocm/lib"; has_ld = true; }
            env_s.push_back(s);
        }
        if (!has_ld) env_s.push_back("LD_LIBRARY_PATH=/opt/rocm/lib");
        std::vector<char *> envp;
        for (auto & e : env_s) envp.push_back(e.data());
        envp.push_back(nullptr);
        std::string cwd = m_.strata_cwd.empty() ? "" : expand_home(m_.strata_cwd);

        int to_child[2], from_child[2];
        if (pipe2(to_child, O_CLOEXEC) != 0 || pipe2(from_child, O_CLOEXEC) != 0) throw std::runtime_error("strata: pipe failed");
        pid_t pid = fork();
        if (pid < 0) throw std::runtime_error("strata: fork failed");
        if (pid == 0) {
            prctl(PR_SET_PDEATHSIG, SIGTERM);
            dup2(to_child[0], 0);
            dup2(from_child[1], 1);
            dup2(log_fd >= 0 ? log_fd : open("/dev/null", O_WRONLY), 2);
            syscall(SYS_close_range, 3u, ~0u, 0u);
            if (!cwd.empty() && chdir(cwd.c_str()) != 0) _exit(126);
            execve(argv[0], argv.data(), envp.data());
            _exit(127);
        }
        close(to_child[0]);
        close(from_child[1]);
        if (log_fd >= 0) close(log_fd);
        pid_ = pid;
        in_fd_ = to_child[1];
        out_fd_ = from_child[0];
        t_start_ = clk::now();
        reader_ = std::thread([this] { read_loop(); });
    }

    void read_loop() {
        std::string buf;
        char tmp[4096];
        for (;;) {
            ssize_t n = read(out_fd_, tmp, sizeof tmp);
            if (n <= 0) break;
            buf.append(tmp, (size_t) n);
            size_t nl;
            std::vector<StrataLine> got;
            while ((nl = buf.find('\n')) != std::string::npos) {
                got.push_back(parse_strata_line(buf.substr(0, nl)));
                buf.erase(0, nl + 1);
            }
            if (!got.empty()) {
                std::lock_guard lk(q_mu_);
                for (auto & g : got) q_.push_back(std::move(g));
                q_cv_.notify_all();
            }
        }
        eof_ = true;
        std::lock_guard lk(q_mu_);
        q_cv_.notify_all();
    }

    // Pops the next line, waiting up to wait_ms. false = nothing arrived (or the engine is gone: eof_ is set).
    bool next_line(StrataLine & out, int wait_ms, bool * gone) {
        std::unique_lock lk(q_mu_);
        if (q_.empty() && wait_ms > 0) q_cv_.wait_for(lk, std::chrono::milliseconds(wait_ms), [&] { return !q_.empty() || eof_.load(); });
        if (q_.empty()) {
            if (gone && eof_.load()) *gone = true;
            return false;
        }
        out = std::move(q_.front());
        q_.pop_front();
        return true;
    }

    bool write_all(const std::string & s) {
        std::lock_guard lk(w_mu_);
        size_t off = 0;
        while (off < s.size()) {
            ssize_t n = write(in_fd_, s.data() + off, s.size() - off);
            if (n <= 0) return false;
            off += (size_t) n;
        }
        return true;
    }

    const Config cfg_;
    ModelConfig m_;
    std::string name_, path_, log_path_;
    llama_model * vocab_model_ = nullptr;
    const llama_vocab * vocab_ = nullptr;
    common_chat_templates_ptr tmpls_;
    pid_t pid_ = -1;
    int in_fd_ = -1, out_fd_ = -1;
    std::thread reader_;
    std::mutex q_mu_, w_mu_;
    mutable std::mutex stat_mu_;
    std::condition_variable q_cv_;
    std::deque<StrataLine> q_;
    std::atomic<bool> eof_{false};
    bool can_stop_ = false;
    int max_context_ = 0;
    clk::time_point t_start_;
    TicketQueue turn_;
    int active_ = 0, ctx_used_ = 0, cur_prio_ = 1;
    std::string cur_tag_, cur_phase_ = "idle";
    long long total_p_ = 0, total_c_ = 0, requests_ = 0, call_ids_ = 0;
    double last_tps_ = 0;
};

