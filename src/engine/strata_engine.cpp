// Test hook: tokenize with the same vocab-only path the engine uses. 0 = ok.
int strata_tokenizer_probe(const std::string & gguf, const std::string & text, std::vector<int> & out) {
    llama_backend_init();
    llama_model * m = load_vocab_model(gguf, (std::filesystem::temp_directory_path() / "judas-strata-probe").string());
    const llama_vocab * v = llama_model_get_vocab(m);
    int n = -llama_tokenize(v, text.c_str(), text.size(), nullptr, 0, llama_vocab_get_add_bos(v), true);
    std::vector<llama_token> t(n);
    llama_tokenize(v, text.c_str(), text.size(), t.data(), n, llama_vocab_get_add_bos(v), true);
    out.assign(t.begin(), t.end());
    llama_model_free(m);
    return 0;
}

