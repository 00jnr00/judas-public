#!/usr/bin/env python3
"""Regenerate web/fonts.css from the files in web/fonts/ (run after adding a font; keep fonts.js catalog in step)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "web", "fonts.css")
# family, file stem, "var" (variable wght axis range) or list of (weight, stem-suffix) statics, has italic
FAMILIES = [
    ("Inter", "inter", "100 900", True),
    ("IBM Plex Sans", "ibm-plex-sans", [(400, ""), (700, "")], True),
    ("Atkinson Hyperlegible", "atkinson-hyperlegible", [(400, ""), (700, "")], True),
    ("Lexend", "lexend", "100 900", False),
    ("Source Sans 3", "source-sans-3", "200 900", True),
    ("Nunito Sans", "nunito-sans", "200 1000", True),
    ("Space Grotesk", "space-grotesk", "300 700", False),
    ("Literata", "literata", "200 900", True),
    ("Source Serif 4", "source-serif-4", "200 900", True),
    ("Lora", "lora", "400 700", True),
    ("JetBrains Mono", "jetbrains-mono", "100 800", True),
    ("IBM Plex Mono", "ibm-plex-mono", [(400, ""), (700, "")], True),
    ("Fira Code", "fira-code", "300 700", False),
    ("Source Code Pro", "source-code-pro", "200 900", True),
    ("Commit Mono", "commit-mono", [(400, ""), (700, "")], True),
    ("Space Mono", "space-mono", [(400, ""), (700, "")], True),
]
def face(fam, url, style, weight):
    return ('@font-face{font-family:"%s";font-style:%s;font-weight:%s;font-display:swap;'
            'src:url("/fonts/%s") format("woff2")}\n' % (fam, style, weight, url))
out = ["/* Bundled fonts (SIL OFL 1.1), Latin subset woff2 served by Judas itself; no CDN. Generated by tools/gen-fonts-css.py.\n"
       "   Licenses: LICENSES/fonts/, THIRD_PARTY.md. Framed pages on this origin may <link> this file (docs/THEMES.md). */\n"]
for fam, stem, w, ital in FAMILIES:
    if isinstance(w, str):
        out.append(face(fam, stem + ".woff2", "normal", w))
        if ital: out.append(face(fam, stem + "-italic.woff2", "italic", w))
    else:
        for wt, _ in w:
            out.append(face(fam, "%s-%d.woff2" % (stem, wt), "normal", wt))
            if ital and os.path.exists(os.path.join(HERE, "..", "web", "fonts", "%s-%di.woff2" % (stem, wt))):
                out.append(face(fam, "%s-%di.woff2" % (stem, wt), "italic", wt))
open(OUT, "w").write("".join(out))
