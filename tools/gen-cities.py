#!/usr/bin/env python3
"""Generate src/location/cities_data.cpp from GeoNames files (development-time only; the binary needs nothing at runtime).

  tools/gen-cities.py cities15000.txt admin1CodesASCII.txt countryInfo.txt > src/location/cities_data.cpp

Data: GeoNames (https://www.geonames.org), CC BY 4.0; see LICENSES/GEONAMES.md.
Blob layout (before LZ4 block compression), little endian:
  u32 n_cities, u16 n_countries, u16 n_regions
  countries: n_countries x (2-byte ISO code, name, NUL)
  regions:   n_regions x (name, NUL); region 0 is "" (none)
  names:     n_cities x (UTF-8 name, NUL)
  country index u16 x n_cities, region index u16 x n_cities
  lat x n_cities as 3 bytes, (lat + 90) * 1000 rounded
  lon x n_cities as 3 bytes, (lon + 180) * 1000 rounded
Cities are sorted by country, then name, so the name block compresses well.
"""
import struct
import sys


def lz4_block(data: bytes) -> bytes:
    n = len(data)
    out = bytearray()
    table = {}
    i = anchor = 0

    def emit(lit_start, lit_end, match_off=None, match_len=0):
        ll = lit_end - lit_start
        token = (min(ll, 15) << 4)
        ml = match_len - 4 if match_off is not None else 0
        if match_off is not None:
            token |= min(ml, 15)
        out.append(token)
        if ll >= 15:
            r = ll - 15
            while r >= 255:
                out.append(255)
                r -= 255
            out.append(r)
        out.extend(data[lit_start:lit_end])
        if match_off is not None:
            out.extend(struct.pack("<H", match_off))
            if ml >= 15:
                r = ml - 15
                while r >= 255:
                    out.append(255)
                    r -= 255
                out.append(r)

    while i + 4 <= n:
        key = data[i:i + 4]
        cand = table.get(key)
        table[key] = i
        if cand is not None and i - cand <= 65535:
            ml = 4
            while i + ml < n and data[cand + ml] == data[i + ml]:
                ml += 1
            emit(anchor, i, i - cand, ml)
            i += ml
            anchor = i
        else:
            i += 1
    emit(anchor, n)
    return bytes(out)


def main():
    cities_f, admin_f, country_f = sys.argv[1:4]
    countries = {}
    for line in open(country_f, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        p = line.rstrip("\n").split("\t")
        countries[p[0]] = p[4]
    admin = {}
    for line in open(admin_f, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        admin[p[0]] = p[2] or p[1]   # ASCII name column
    rows = []
    for line in open(cities_f, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        name, lat, lon, cc, a1 = p[1], float(p[4]), float(p[5]), p[8], p[10]
        rows.append((cc, name, lat, lon, admin.get(cc + "." + a1, "")))
    rows.sort(key=lambda r: (r[0], r[1]))
    cc_list = sorted({r[0] for r in rows})
    cc_idx = {c: i for i, c in enumerate(cc_list)}
    regions = [""]
    reg_idx = {"": 0}
    for r in rows:
        if r[4] not in reg_idx:
            reg_idx[r[4]] = len(regions)
            regions.append(r[4])
    b = bytearray(struct.pack("<IHH", len(rows), len(cc_list), len(regions)))
    for c in cc_list:
        b += c.encode("ascii") + countries.get(c, c).encode("utf-8") + b"\0"
    for rg in regions:
        b += rg.encode("utf-8") + b"\0"
    for r in rows:
        b += r[1].encode("utf-8") + b"\0"
    for r in rows:
        b += struct.pack("<H", cc_idx[r[0]])
    for r in rows:
        b += struct.pack("<H", reg_idx[r[4]])
    for r in rows:
        b += struct.pack("<I", round((r[2] + 90) * 1000))[:3]
    for r in rows:
        b += struct.pack("<I", round((r[3] + 180) * 1000))[:3]
    raw = bytes(b)
    comp = lz4_block(raw)
    sys.stderr.write("cities %d, raw %d bytes, lz4 %d bytes\n" % (len(rows), len(raw), len(comp)))
    print("// GENERATED by tools/gen-cities.py from GeoNames cities15000 (CC BY 4.0, https://www.geonames.org). Do not edit.")
    print('#include "location/cities.h"')
    print("namespace judas::location {")
    print("const unsigned long kCitiesRawSize = %d;" % len(raw))
    print("const unsigned long kCitiesPackedSize = %d;" % len(comp))
    print("const unsigned char kCitiesPacked[] = {")
    line = []
    for i, v in enumerate(comp):
        line.append(str(v))
        if len(line) == 40:
            print(",".join(line) + ",")
            line = []
    if line:
        print(",".join(line))
    print("};")
    print("}  // namespace judas::location")


main()
